package net.chickalo.bugsbugsandmorebugs.worldgen.tree;

import com.mojang.serialization.MapCodec;
import net.chickalo.bugsbugsandmorebugs.block.ModBlocks;
import net.chickalo.bugsbugsandmorebugs.block.custom.ForestRootsBlock;
import net.chickalo.bugsbugsandmorebugs.block.custom.HangingAccentBlock;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.tags.BlockTags;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.levelgen.feature.treedecorators.TreeDecorator;
import net.minecraft.world.level.levelgen.feature.treedecorators.TreeDecoratorType;

/** Willow leaves and roots added to trees generated by vanilla FancyTrunkPlacer. */
public final class WillowDecorator extends TreeDecorator {
    public static final MapCodec<WillowDecorator> CODEC=MapCodec.unit(new WillowDecorator());
    @Override protected TreeDecoratorType<?> type() { return ModTreeDecoratorTypes.WILLOW_DECORATOR; }
    @Override public void place(Context context) {
        var random=context.random();
        // Uneven, relatively sparse hanging foliage, not a leaf-filled sphere.
        for (BlockPos leaf: context.leaves()) {
            if (random.nextInt(9)!=0 || !context.isAir(leaf.below()))continue;
            if (!context.checkBlock(leaf,s->s.is(ModBlocks.WILLOW_LEAVES)))continue;
            int count=1+random.nextInt(5);
            int made=0;
            for(int d=1;d<=count;d++){
                BlockPos at=leaf.below(d);
                if(!context.isAir(at))break;
                context.setBlock(at,ModBlocks.HANGING_WILLOW_LEAVES.defaultBlockState()
                        .setValue(HangingAccentBlock.TIP,false));
                made++;
            }
            if(made>0)context.setBlock(leaf.below(made),
                    ModBlocks.HANGING_WILLOW_LEAVES.defaultBlockState()
                            .setValue(HangingAccentBlock.TIP,true));
        }
        // A few short aerial roots attached to the bottom of the trunk.
        // The 3D root blocks now inherit the actual vanilla mangrove-roots model.
        BlockPos lowest=null;
        for(BlockPos log:context.logs())
            if(lowest==null||log.getY()<lowest.getY())lowest=log;
        if(lowest==null)return;
        Direction[] directions={Direction.NORTH,Direction.EAST,Direction.SOUTH,Direction.WEST};
        for(Direction dir:directions){
            if(random.nextFloat()<0.28F)continue;
            BlockPos start=lowest.above().relative(dir);
            BlockPos landing=lowest.relative(dir,2);
            boolean dry=context.checkBlock(landing.below(),s->s.is(BlockTags.DIRT));
            boolean water=context.checkBlock(landing,s->s.is(Blocks.WATER));
            if(!dry && !water)continue;
            BlockPos middle=lowest.relative(dir).above();
            if(context.isAir(start))
                context.setBlock(start,ModBlocks.WILLOW_ROOTS.defaultBlockState()
                        .setValue(BlockStateProperties.AXIS,dir.getAxis())
                        .setValue(ForestRootsBlock.WATERLOGGED,false));
            if(context.isAir(middle))
                context.setBlock(middle,ModBlocks.WILLOW_ROOTS.defaultBlockState()
                        .setValue(BlockStateProperties.AXIS,dir.getAxis())
                        .setValue(ForestRootsBlock.WATERLOGGED,false));
            if(context.isAir(landing)||water)
                context.setBlock(landing,ModBlocks.WILLOW_ROOTS.defaultBlockState()
                        .setValue(BlockStateProperties.AXIS,dir.getAxis())
                        .setValue(ForestRootsBlock.WATERLOGGED,water));
        }
    }
}
